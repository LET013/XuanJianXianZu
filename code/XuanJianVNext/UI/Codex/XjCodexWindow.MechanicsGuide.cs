    private void DrawMechanicsNavigation()
    {
        string[] labels = { "查看修道大势", "查看果位权柄", "查看道途总览", "查看释修总览", "查看玄鉴史册" };
        int[] tabs = { 14, 18, 21, 22, 11 };
        const float gap = 6f;
        float usable = Mathf.Max(360f, ContentWidth - 34f);
        float buttonWidth = Mathf.Max(118f, (usable - gap * (labels.Length - 1)) / labels.Length);

        GUILayout.BeginHorizontal(GUILayout.ExpandWidth(true));
        for (int i = 0; i < labels.Length; i++)
        {
            if (i > 0) GUILayout.Space(gap);
            if (GUILayout.Button(labels[i], GUILayout.Width(buttonWidth), GUILayout.Height(32f))) SelectCodexTab(tabs[i]);
        }
        GUILayout.FlexibleSpace();
        GUILayout.EndHorizontal();
        GUILayout.Space(5f);
    }

    private void DrawMechanicsGuidePicker()
    {
        const float gap = 6f;
        const int columns = 4;
        float usable = Mathf.Max(360f, ContentWidth - 34f);
        float buttonWidth = Mathf.Max(96f, (usable - gap * (columns - 1)) / columns);

        // 同一行始终使用相同的固定单元宽度；不足一整行时保留等宽空位，
        // 不再让最后一行依靠 ExpandWidth 被拉长，避免百科入口出现层次不齐。
        GUILayout.BeginVertical(GUI.skin.box, GUILayout.ExpandWidth(true));
        for (int i = 0; i < MechanicsGuideViews.Length; i += columns)
        {
            GUILayout.BeginHorizontal(GUILayout.ExpandWidth(true));
            for (int column = 0; column < columns; column++)
            {
                if (column > 0) GUILayout.Space(gap);
                int index = i + column;
                if (index >= MechanicsGuideViews.Length)
                {
                    GUILayout.Space(buttonWidth);
                    continue;
                }

                string view = MechanicsGuideViews[index];
                GUI.backgroundColor = string.Equals(_mechanicsGuideView, view, StringComparison.Ordinal)
                    ? new Color(0.48f, 0.58f, 0.55f, 1f)
                    : new Color(0.24f, 0.25f, 0.28f, 1f);
                if (GUILayout.Button(view, GUILayout.Width(buttonWidth), GUILayout.Height(38f)))
                {
                    _mechanicsGuideView = view;
                    _scrollPosition = Vector2.zero;
                }
            }
            GUILayout.FlexibleSpace();
            GUILayout.EndHorizontal();
        }
        GUI.backgroundColor = Color.white;
        GUILayout.EndVertical();
        GUILayout.Space(6f);
    }

