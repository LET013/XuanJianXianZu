/// 既有神通、易象关系和现行道途设定作出的体系化演绎，不冒充原著逐字设定。
/// </summary>
internal readonly struct XjAuthorityLoreEntry
{
	internal readonly string AuthorityName;
	internal readonly string Doctrine;
	internal readonly string Domain;
	internal readonly string Boundary;
	internal readonly string BoundShenTong;

	internal XjAuthorityLoreEntry(string authorityName, string doctrine, string domain, string boundary, string boundShenTong)
	{
		AuthorityName = authorityName ?? string.Empty;
		Doctrine = doctrine ?? string.Empty;
		Domain = domain ?? string.Empty;
		Boundary = boundary ?? string.Empty;
		BoundShenTong = boundShenTong ?? string.Empty;
	}
}

