	internal static IReadOnlyList<XjAuthorityLoreEntry> Get(string daoTu)
	{
		return !string.IsNullOrWhiteSpace(daoTu) && Entries.TryGetValue(daoTu.Trim(), out XjAuthorityLoreEntry[] values)
			? values
			: Array.Empty<XjAuthorityLoreEntry>();
	}

	internal static bool TryResolveAuthorityForShenTong(string daoTu, string shenTongNameOrId, out string authorityName)
	{
		authorityName = string.Empty;
		string normalizedDaoTu = (daoTu ?? string.Empty).Trim();
		if (normalizedDaoTu.Length == 0 || !Entries.TryGetValue(normalizedDaoTu, out XjAuthorityLoreEntry[] entries)) return false;

		string canonicalShenTong = (shenTongNameOrId ?? string.Empty).Trim();
		if (XjZiJinUpperShenTongCatalog.TryGet(canonicalShenTong, out XjZiJinUpperShenTongDefinition definition)
			&& string.Equals(definition.DaoTuDisplayName, normalizedDaoTu, StringComparison.Ordinal))
		{
			canonicalShenTong = definition.DisplayName;
		}
		if (canonicalShenTong.Length == 0) return false;

		// 并古与长庚优先复用真实的“权柄→下位→上位”易象表；渊照、虹霞则由本目录
		// 的 BoundShenTong 直接承接。两条路径最后都必须落回同一份独立权柄目录。
		if (XjAuthorityShenTongMutationCatalog.TryResolveLocalAuthorityForUpper(normalizedDaoTu, canonicalShenTong, out string mappedAuthority))
		{
			mappedAuthority = XjGuoWeiAuthorityCatalog.NormalizeAuthorityName(normalizedDaoTu, mappedAuthority);
			for (int i = 0; i < entries.Length; i++)
			{
				if (!string.Equals(entries[i].AuthorityName, mappedAuthority, StringComparison.Ordinal)) continue;
				authorityName = mappedAuthority;
				return true;
			}
		}

		for (int i = 0; i < entries.Length; i++)
		{
			XjAuthorityLoreEntry entry = entries[i];
			if (entry.BoundShenTong.Length == 0) continue;
			string bound = ResolveBoundShenTongDisplay(entry.BoundShenTong, normalizedDaoTu);
			if (!string.Equals(bound, canonicalShenTong, StringComparison.Ordinal)) continue;
			authorityName = entry.AuthorityName;
			return authorityName.Length > 0;
		}
		return false;
	}

	internal static string BuildSummary(string daoTu)
	{
		IReadOnlyList<XjAuthorityLoreEntry> entries = Get(daoTu);
		if (entries.Count == 0) return string.Empty;
		List<string> parts = new List<string>(entries.Count);
		for (int i = 0; i < entries.Count; i++)
		{
			XjAuthorityLoreEntry entry = entries[i];
			if (string.IsNullOrWhiteSpace(entry.AuthorityName)) continue;
			string binding = string.IsNullOrWhiteSpace(entry.BoundShenTong)
				? "根柄"
				: "承「" + ResolveBoundShenTongDisplay(entry.BoundShenTong, daoTu) + "」";
			parts.Add(entry.AuthorityName + "〔" + binding + "〕：法理——" + entry.Doctrine
				+ " 主掌——" + entry.Domain + " 边界——" + entry.Boundary);
		}
		return string.Join("；", parts);
	}

	private static string ResolveBoundShenTongDisplay(string value, string daoTu)
	{
		if (XjZiJinUpperShenTongCatalog.TryGet(value, out XjZiJinUpperShenTongDefinition definition)
			&& string.Equals(definition.DaoTuDisplayName, (daoTu ?? string.Empty).Trim(), StringComparison.Ordinal)
			&& !string.IsNullOrWhiteSpace(definition.DisplayName))
		{
			return definition.DisplayName;
		}
		return string.IsNullOrWhiteSpace(value) ? "未名神通" : value.Trim();
	}

	private static XjAuthorityLoreEntry E(string authorityName, string doctrine, string domain, string boundary, string boundShenTong = "")
	{
		return new XjAuthorityLoreEntry(authorityName, doctrine, domain, boundary, boundShenTong);
	}
