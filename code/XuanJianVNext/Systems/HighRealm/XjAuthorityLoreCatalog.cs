/// <summary>
/// 后置道途权柄法理目录。
///
/// 阴阳、三雷、五德、十二炁的六柄从来不是“六门神通换名”，而是先有独立天道权柄，
/// 再由其中五柄向下承接具体上位神通。后置道途统一采用同一结构：一柄总纲/根柄，
