	internal static string GenerateCaiQiFaName(string daoTu, long seed)
	{
		string normalizedDaoTu = (daoTu ?? string.Empty).Trim();
		if (string.IsNullOrWhiteSpace(normalizedDaoTu)
			|| string.Equals(normalizedDaoTu, "基础", StringComparison.Ordinal)
			|| string.Equals(normalizedDaoTu, "玄门", StringComparison.Ordinal)
			|| string.Equals(normalizedDaoTu, "无道途", StringComparison.Ordinal))
		{
			return string.Empty;
		}

		if (!CaiQiFaNameMap.TryGetValue(normalizedDaoTu, out string[] names) || names == null || names.Length == 0)
		{
			return string.Empty;
		}

		return names[XjDeterministicHash.PositiveIndex(seed, normalizedDaoTu, names.Length)];
	}

